"""Export the synthetic RevenueRescue dataset to model-ready CSV files.

The source Parquet data is generated by ``bigdata.ingestion.generate_dataset``.
This exporter reads Parquet files one-by-one so partition columns with mixed
Arrow integer widths do not prevent loading the dataset.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

import pandas as pd


EVENT_COLUMNS = [
    "schema_version",
    "event_id",
    "event_type",
    "customer_id",
    "amount_paise",
    "currency",
    "failure_reason",
    "occurred_at",
    "payment_method",
    "device_type",
    "country",
    "retry_count",
    "recovered",
    "is_synthetic",
]

CUSTOMER_COLUMNS = [
    "customer_id",
    "segment",
    "country",
    "account_age_days",
    "lifetime_value_paise",
    "average_transaction_value_paise",
    "transaction_count",
    "successful_transactions",
    "failed_transactions",
    "failure_rate",
    "payment_success_rate",
    "subscription_age_days",
    "subscription_status",
    "payment_method",
    "communication_preferences",
    "previous_recovery_count",
    "previous_recovery_success_rate",
    "is_synthetic",
]


def read_parquet_files(root: Path) -> pd.DataFrame:
    files = sorted(root.rglob("*.parquet"))
    if not files:
        raise FileNotFoundError(f"No Parquet files found under {root}")
    frames = [pd.read_parquet(path) for path in files]
    return pd.concat(frames, ignore_index=True)


def stable_split(event_id: str) -> str:
    bucket = int(hashlib.sha256(event_id.encode("utf-8")).hexdigest()[:8], 16) % 100
    if bucket < 70:
        return "train"
    if bucket < 85:
        return "validation"
    return "test"


def build_customer_history(events: pd.DataFrame) -> pd.DataFrame:
    frame = events.copy()
    frame["recovered_int"] = frame["recovered"].fillna(False).astype(int)
    frame["checkout_abandonment"] = (frame["event_type"] == "CHECKOUT_ABANDONED").astype(int)
    frame["failure_count"] = 1

    history = frame.groupby("customer_id", sort=True).agg(
        transaction_count=("event_id", "count"),
        failure_count=("failure_count", "sum"),
        success_count=("recovered_int", "sum"),
        average_amount_paise=("amount_paise", "mean"),
        total_amount_paise=("amount_paise", "sum"),
        retry_count_mean=("retry_count", "mean"),
        checkout_abandonment_count=("checkout_abandonment", "sum"),
    ).reset_index()
    history["failure_rate"] = history["failure_count"] / history["transaction_count"]
    history["checkout_abandonment_rate"] = (
        history["checkout_abandonment_count"] / history["transaction_count"]
    )
    history["previous_recovery_rate"] = history["success_count"] / history["transaction_count"]
    history["revenue_at_risk_paise"] = history["total_amount_paise"]
    history["has_recovered"] = (history["success_count"] > 0).astype("int8")
    return history[
        [
            "customer_id",
            "transaction_count",
            "failure_count",
            "success_count",
            "failure_rate",
            "average_amount_paise",
            "total_amount_paise",
            "retry_count_mean",
            "checkout_abandonment_rate",
            "previous_recovery_rate",
            "revenue_at_risk_paise",
            "has_recovered",
        ]
    ]


def export(source: Path, output: Path) -> dict[str, object]:
    events = read_parquet_files(source / "bronze" / "payment_events")
    customers = read_parquet_files(source / "bronze" / "customers")

    events = events.drop_duplicates(subset=["event_id"]).sort_values("event_id").reset_index(drop=True)
    events["occurred_at"] = pd.to_datetime(events["occurred_at"], utc=True).dt.strftime("%Y-%m-%dT%H:%M:%SZ")
    events["recovered"] = events["recovered"].fillna(False).astype(bool)
    events["is_synthetic"] = events["is_synthetic"].fillna(True).astype(bool)
    events["split"] = events["event_id"].map(stable_split)
    events = events[EVENT_COLUMNS + ["split"]]

    customers = customers.drop_duplicates(subset=["customer_id"]).sort_values("customer_id").reset_index(drop=True)
    customers = customers[CUSTOMER_COLUMNS]

    output.mkdir(parents=True, exist_ok=True)
    events.to_csv(output / "payment_events.csv", index=False)
    events.loc[events["split"] == "train"].drop(columns=["split"]).to_csv(output / "train.csv", index=False)
    events.loc[events["split"] == "validation"].drop(columns=["split"]).to_csv(output / "validation.csv", index=False)
    events.loc[events["split"] == "test"].drop(columns=["split"]).to_csv(output / "test.csv", index=False)
    customers.to_csv(output / "customer_profiles.csv", index=False)
    build_customer_history(events.drop(columns=["split"])).to_csv(
        output / "customer_history_features.csv", index=False
    )

    manifest = {
        "dataset_version": "synthetic-payment-events.v1",
        "source": str(source),
        "output": str(output),
        "customers": int(len(customers)),
        "events": int(len(events)),
        "split_counts": {key: int((events["split"] == key).sum()) for key in ("train", "validation", "test")},
        "files": [
            "payment_events.csv",
            "train.csv",
            "validation.csv",
            "test.csv",
            "customer_profiles.csv",
            "customer_history_features.csv",
        ],
        "target_column": "recovered",
        "label_semantics": "synthetic outcome for model training only; operational recovery remains verifier-authoritative",
        "all_data_is_synthetic": True,
    }
    (output / "training_manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    return manifest


def main() -> None:
    project_root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=Path(r"C:\Users\moury\data"))
    parser.add_argument("--output", type=Path, default=project_root / "data" / "training")
    args = parser.parse_args()
    print(json.dumps(export(args.source, args.output), indent=2))


if __name__ == "__main__":
    main()
