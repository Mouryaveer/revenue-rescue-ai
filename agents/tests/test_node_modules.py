"""
Module-boundary tests for the node split (improve-architecture Requirement 1).
"""

import ast
import subprocess
import sys
from pathlib import Path

NODES_DIR = Path(__file__).resolve().parents[1] / "nodes"
REPO_ROOT = Path(__file__).resolve().parents[2]


def _imported_modules(path: Path) -> set[str]:
    tree = ast.parse(path.read_text(encoding="utf-8"))
    mods: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom) and node.module:
            mods.add(node.module)
        elif isinstance(node, ast.Import):
            mods.update(alias.name for alias in node.names)
    return mods


def test_nodes_py_removed():
    assert not (NODES_DIR / "nodes.py").exists()


def test_llm_and_deterministic_modules_do_not_import_each_other():
    llm_imports = _imported_modules(NODES_DIR / "llm_nodes.py")
    det_imports = _imported_modules(NODES_DIR / "deterministic_nodes.py")
    assert "agents.nodes.deterministic_nodes" not in llm_imports
    assert "agents.nodes.llm_nodes" not in det_imports
    assert "agents.nodes.node_utils" in llm_imports
    assert "agents.nodes.node_utils" in det_imports


def test_deterministic_nodes_import_without_llm_modules():
    """Importing deterministic nodes in a fresh interpreter must not load LLM code."""
    code = (
        "import sys\n"
        "import agents.nodes.deterministic_nodes\n"
        "bad = [m for m in ('agents.nodes.llm_provider', 'agents.nodes.llm_nodes') "
        "if m in sys.modules]\n"
        "assert not bad, bad\n"
    )
    pythonpath = f"{REPO_ROOT}{';' if sys.platform == 'win32' else ':'}{REPO_ROOT / 'backend'}"
    result = subprocess.run(
        [sys.executable, "-c", code],
        cwd=REPO_ROOT,
        env={**__import__("os").environ, "PYTHONPATH": pythonpath},
        capture_output=True,
        text=True,
        timeout=60,
    )
    assert result.returncode == 0, result.stderr


def test_graph_wires_nodes_from_split_modules():
    graph_imports = _imported_modules(REPO_ROOT / "agents" / "graph" / "recovery_graph.py")
    assert "agents.nodes.llm_nodes" in graph_imports
    assert "agents.nodes.deterministic_nodes" in graph_imports
    assert "agents.nodes.nodes" not in graph_imports
